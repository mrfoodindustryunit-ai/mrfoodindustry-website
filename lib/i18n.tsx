export type TranslationNamespace = keyof typeof translations.en
export type TranslationKey = `${TranslationNamespace}.${string}`

const LanguageContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void } | undefined>(undefined)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en')
  const [ready, setReady] = useState(false)

  useEffect(() => {
    const saved = window.localStorage.getItem('mr-industries-language')
    const nextLocale = saved === 'kn' ? 'kn' : 'en'
    setLocaleState(nextLocale)
    setReady(true)
  }, [])

  useEffect(() => {
    if (!ready) return
    document.documentElement.lang = locale
    document.documentElement.setAttribute('data-locale', locale)
    window.localStorage.setItem('mr-industries-language', locale)
  }, [locale, ready])

  return <LanguageContext.Provider value={{ locale, setLocale: setLocaleState }}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider')
  }
  return context
}

function resolveTranslation(locale: Locale, path: string, values?: Record<string, string | number>) {
  const segments = path.split('.')
  let current: unknown = translations[locale]

  for (const segment of segments) {
    if (current && typeof current === 'object' && segment in current) {
      current = (current as Record<string, unknown>)[segment]
    } else {
      return path
    }
  }

  if (typeof current === 'string') {
    return current.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, key: string) => String(values?.[key] ?? ''))
  }

  return current ?? path
}

export function translate(locale: Locale, path: string, values?: Record<string, string | number>): string {
  const result = resolveTranslation(locale, path, values)
  return typeof result === 'string' ? result : path
}

export function translateData(locale: Locale, path: string) {
  return resolveTranslation(locale, path)
}

export function useTranslation() {
  const { locale, setLocale } = useLanguage()

  return {
    locale,
    setLocale,
    isKannada: locale === 'kn',
    t: (path: TranslationKey, values?: Record<string, string | number>) => translate(locale, path, values),
    data: (path: TranslationKey) => translateData(locale, path),
  }
}

export function getLocaleLabel(locale: Locale) {
  return locale === 'kn' ? 'ಕನ್ನಡ' : 'EN'
}
